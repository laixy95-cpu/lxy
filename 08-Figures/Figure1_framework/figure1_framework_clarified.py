    box(x, y + h - title_height, w, title_height,
        palette["header"], palette["edge"], z=3)
    ax.add_patch(Rectangle((x + .08, y + h - title_height), w - .16,
                           title_height / 2, color=palette["header"], linewidth=0, zorder=4))
    label(x + w / 2, y + h - title_height / 2, title, FONT_CARD,
          (x, y + h - title_height, x + w, y + h), title)
    return bounds


