def map_thumbnail(x, y, w, h, palette):
    sx, sy = w, h
    for role, missing, rings in MAP_GEOMETRY:
        for ring in rings:
            points = [(x + u * sx, y + v * sy) for u, v in ring]
            if role == "city":
                ax.add_patch(Polygon(points, closed=True,
                    facecolor="#F3F3F3" if missing else palette["header"],
                    edgecolor=palette["edge"], linewidth=.20, zorder=4))
            else:
                ax.add_patch(Polygon(points, closed=True, facecolor="none",
                    edgecolor="#4A8398", linewidth=.45, zorder=5))


def endpoint_plot(x, y, w, h, points, title, palette, fmt, bounds):
    label(x + w / 2, y + h + 1.7, title, FONT_SMALL, bounds, title)
    xs = [x + 1.1, x + w - 1.1]
    values = [value for _, value in points]
    low, high = min(values), max(values)
    ys = [y + 1.2 + (value - low) / (high - low) * (h - 3.0) for value in values]
    ax.add_line(Line2D(xs, ys, linewidth=1.1, color=palette["edge"], zorder=6))
    ax.scatter(xs, ys, s=9, color=palette["bar"], edgecolor=palette["edge"], linewidth=.5, zorder=7)
    for (year, value), xx, yy in zip(points, xs, ys):
        label(xx, yy + 1.45, fmt.format(value), FONT_SMALL, bounds, title + " value")
        label(xx, y - .8, str(year), FONT_SMALL, bounds, title + " year")


