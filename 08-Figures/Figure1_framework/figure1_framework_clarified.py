def check_layout():
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    problems = []
    for text, bounds, tag in TEXT_CHECKS:
        if text.get_fontsize() < 5.5:
            problems.append(f"Small text: {text.get_text()}")
        if text.get_color() != TEXT:
            problems.append(f"Text colour: {text.get_text()}")
        bb = text.get_window_extent(renderer)
        if bounds is not None:
            (x0, y0), (x1, y1) = ax.transData.transform([(bounds[0], bounds[1]), (bounds[2], bounds[3])])
            if bb.x0 < x0 - .6 or bb.x1 > x1 + .6 or bb.y0 < y0 - .6 or bb.y1 > y1 + .6:
                problems.append(f"Overflow [{tag}]: {text.get_text()}")
    for i, (a, _, _) in enumerate(TEXT_CHECKS):
        bba = a.get_window_extent(renderer)
        for b, _, _ in TEXT_CHECKS[i + 1:]:
            bbb = b.get_window_extent(renderer)
            if min(bba.x1, bbb.x1) - max(bba.x0, bbb.x0) > 1 and min(bba.y1, bbb.y1) - max(bba.y0, bbb.y0) > 1:
                problems.append(f"Text overlap: {a.get_text()} / {b.get_text()}")
    for arrow in ARROWS:
        abb = arrow.get_window_extent(renderer)
        for text, _, _ in TEXT_CHECKS:
            bb = text.get_window_extent(renderer)
            if abb.overlaps(bb):
                problems.append(f"Arrow overlaps text: {text.get_text()}")
    print(f"Font {FONT}; {len(TEXT_CHECKS)} labels; minimum {min(t.get_fontsize() for t, _, _ in TEXT_CHECKS):.1f} pt")
    for problem in problems:
        print(problem)
    if problems:
        raise RuntimeError(f"Layout QA found {len(problems)} issue(s)")
    print("Layout QA passed")


